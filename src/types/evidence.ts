export interface EvidenceFileDTO {
  id: string;
  /** Original file name, for display only. The storage key is never exposed. */
  name: string;
  mimeType: string;
  sizeBytes: number;
  isImage: boolean;
}

export interface EvidenceDTO {
  id: string;
  /** Main skill (the one counted in skill statistics). */
  talentSkillId: string;
  skillName: string;
  /** Every skill the evidence demonstrates, main one included. */
  skills: { id: string; name: string }[];
  projectId: string | null;
  type: EvidenceType;
  title: string;
  description: string | null;
  /** Project / demo / reference link. */
  url: string | null;
  organization: string | null;
  role: string | null;
  /** "YYYY-MM" */
  startDate: string | null;
  endDate: string | null;
  technologies: string[];
  tags: string[];
  category: string | null;
  visibility: EvidenceVisibility;
  /** false = saved as a draft. */
  published: boolean;
  allowContact: boolean;
  allowRecommendations: boolean;
  files: EvidenceFileDTO[];
  status: EvidenceStatus;
  createdAt: string;
}

/** What the repository persists. File `path` is the storage key, server-side only. */
export interface NewEvidence {
  talentSkillId: string;
  skillIds: string[];
  projectId?: string;
  type: EvidenceType;
  title: string;
  description?: string;
  url?: string;
  organization?: string;
  role?: string;
  startDate?: string;
  endDate?: string;
  technologies: string[];
  tags: string[];
  category?: string;
  visibility: EvidenceVisibility;
  published: boolean;
  allowContact: boolean;
  allowRecommendations: boolean;
  files: { path: string; name: string; mimeType: string; sizeBytes: number }[];
}
