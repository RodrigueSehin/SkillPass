export const URL_EVIDENCE_TYPES: readonly EvidenceType[] = ["LINK", "REPOSITORY", "PORTFOLIO"];

export type UserEvidenceType = (typeof USER_EVIDENCE_TYPES)[number];

export type EvidenceStatus = "UNVERIFIED" | "PENDING" | "VERIFIED";

